import {readFileSync,writeFileSync} from 'node:fs';
const paths=process.argv.slice(2);
if(paths.length!==4)throw Error('Pass four generated rank JSON files in rank order');
const bank=paths.flatMap((path,i)=>{const rows=JSON.parse(readFileSync(path,'utf8'));if(rows.length!==50||rows.some(x=>x.proof.best!==i+1))throw Error('Invalid rank pool');return rows;});
writeFileSync(new URL('./bank-ranked.mjs',import.meta.url),'// Generated by regenerate-ranked.mjs + assemble-ranked.mjs.\nexport const bank='+JSON.stringify(bank)+';\n');
